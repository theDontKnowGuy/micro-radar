#!/usr/bin/env python3
"""Regenerate include/QrCode.h -- the QR code for the project's GitHub page.

The code is stored as its module grid, one bit per module, rather than as
pixels: a QR is drawn by filling squares, and the size of those squares depends
on the panel rather than on the code. QrScreen::Show() in src/ui/QrScreen.cpp
picks the scale and does the filling.

Error correction is left to segno, which raises the level for free whenever a
stronger one fits in the same version -- this URL asks for M and gets Q.

Requires segno. Run from the repo root:

    python3 scripts/generate_qr_code.py
"""

import sys
from pathlib import Path

try:
    import segno
except ImportError:
    sys.exit("missing segno -- pip install segno")

ROOT = Path(__file__).resolve().parent.parent
DST = ROOT / "include" / "QrCode.h"

URL = "https://github.com/thedontknowguy/micro-radar"

# Four modules of clear space on every side, which is what the specification
# asks for and what a phone's decoder looks for before it will believe it has
# found a finder pattern. Drawn by QrScreen rather than baked into the grid
# here, so the grid stays the code itself.
QUIET_ZONE = 4

BYTES_PER_LINE = 12


def pack(matrix):
    """One bit per module, MSB first, each row padded out to a whole byte."""
    size = len(matrix)
    stride = (size + 7) // 8
    rows = []
    for row in matrix:
        packed = bytearray(stride)
        for x, module in enumerate(row):
            if module:
                packed[x // 8] |= 0x80 >> (x % 8)
        rows.append(packed)
    return stride, rows


def emit(url, version, error, size, stride, rows):
    out = [
        "#pragma once",
        "",
        "#include <Arduino.h>",
        "#include <cstdint>",
        "",
        "// Generated by scripts/generate_qr_code.py. Do not edit by hand.",
        "//",
        f"// {url}",
        f"// version {version}, error correction {error}, {size}x{size} modules.",
        "namespace QrCode {",
        "",
        "// What the code says, for the log line that goes out with it.",
        f'constexpr const char* Url = "{url}";',
        "",
        "// Modules per side, without the quiet zone.",
        f"constexpr int Size = {size};",
        "",
        "// Clear modules the code needs around it before a decoder will find it.",
        f"constexpr int QuietZone = {QUIET_ZONE};",
        "",
        "// Bytes per row of Modules; the last one is only partly used.",
        f"constexpr int Stride = {stride};",
        "",
        "// One bit per module, MSB first, dark set.",
        "static const uint8_t Modules[] PROGMEM = {",
    ]

    flat = [f"0x{b:02X}" for row in rows for b in row]
    for j in range(0, len(flat), BYTES_PER_LINE):
        out.append("  " + ", ".join(flat[j:j + BYTES_PER_LINE]) + ",")
    out.append("};")

    out += ["", "}  // namespace QrCode", ""]
    return "\n".join(out)


def main():
    code = segno.make(URL, error="m", micro=False)
    matrix = [list(row) for row in code.matrix]
    size = len(matrix)
    stride, rows = pack(matrix)

    print(f"{URL}")
    print(f"  version {code.version}, error correction {code.error}, "
          f"{size}x{size} modules, {size * stride} bytes")

    DST.write_text(emit(URL, code.version, code.error, size, stride, rows))
    print(f"wrote {DST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
